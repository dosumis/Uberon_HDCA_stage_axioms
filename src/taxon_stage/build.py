"""Generate OWL from the axiom table.

Emits OWL functional syntax, which ROBOT reads directly and which expresses a
GCI without ceremony. The axioms are General Class Inclusions:

    (X and in_taxon some T) SubClassOf existence_starts_during some S

rather than assertions on X itself, because `X SubClassOf
existence_starts_during some S` would be an all-some claim -- it says every X in
every organism starts at S, which is false the moment a second taxon is
considered. The taxon conjunct is what makes the claim sayable.

The cost is that a GCI has no named subject, so nothing materialises it. That is
what sparql/expand.ru exists to fix, and why it operates on this file rather
than being folded in here: the same expansion has to work on GCIs already in
Uberon, which we did not write.
"""

from __future__ import annotations

import datetime
from pathlib import Path

from .model import Axiom, PREDICATES

IN_TAXON = "RO:0002162"

PREFIXES = {
    "owl": "http://www.w3.org/2002/07/owl#",
    "rdf": "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
    "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
    "dcterms": "http://purl.org/dc/terms/",
    "oboInOwl": "http://www.geneontology.org/formats/oboInOwl#",
    "UBERON": "http://purl.obolibrary.org/obo/UBERON_",
    "NCBITaxon": "http://purl.obolibrary.org/obo/NCBITaxon_",
    "HsapDv": "http://purl.obolibrary.org/obo/HsapDv_",
    "MmusDv": "http://purl.obolibrary.org/obo/MmusDv_",
    "RO": "http://purl.obolibrary.org/obo/RO_",
    "ECO": "http://purl.obolibrary.org/obo/ECO_",
    "TSA": "https://w3id.org/taxon-stage-axioms/",
}

ONTOLOGY_IRI = "https://w3id.org/taxon-stage-axioms/axioms.ofn"

# Marks a GCI as one the expansion macro should mint a named class for. Carried
# as an annotation so the macro can be driven by intent, and so a GCI can opt
# out; the macro matches on shape as well, so forgetting it is not fatal.
EXPAND = "TSA:expand_for_reasoning"


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _annotations(a: Axiom) -> list[str]:
    out = [f"Annotation(TSA:onset_type {_quote(a.onset_type)})",
           f"Annotation({EXPAND} \"true\"^^xsd:boolean)"]
    if a.evidence_code:
        out.append(f"Annotation(RO:0002558 {a.evidence_code})")
    if a.evidence_text:
        out.append(f"Annotation(rdfs:comment {_quote(a.evidence_text)})")
    if a.source:
        out.append(f"Annotation(oboInOwl:hasDbXref {_quote(a.source)})")
    if a.curator:
        out.append(f"Annotation(dcterms:contributor {_quote(a.curator)})")
    if a.date:
        out.append(f"Annotation(dcterms:date {_quote(a.date)})")
    return out


def gci(a: Axiom) -> str:
    """One GCI, with its evidence carried as axiom annotations."""
    lhs = (
        f"ObjectIntersectionOf({a.uberon_id} "
        f"ObjectSomeValuesFrom({IN_TAXON} {a.taxon_id}))"
    )
    rhs = f"ObjectSomeValuesFrom({a.predicate} {a.stage_id})"
    anns = "\n    ".join(_annotations(a))
    return f"SubClassOf(\n    {anns}\n    {lhs}\n    {rhs}\n)"


def render(axioms: list[Axiom]) -> str:
    live = [a for a in axioms if a.status != "superseded"]
    lines = [f"Prefix({p}:=<{iri}>)" for p, iri in PREFIXES.items()]
    lines.append("")
    lines.append(f"Ontology(<{ONTOLOGY_IRI}>")
    lines.append(f'Annotation(dcterms:date "{datetime.date.today().isoformat()}")')
    lines.append(
        'Annotation(rdfs:comment "Taxon-scoped existence bounds for Uberon structures, '
        'generated from src/axioms.tsv. Do not edit this file; edit the table.")'
    )
    lines.append("")

    # Declare everything referenced, so the file stands alone without imports.
    declared: set[str] = set()
    for a in live:
        for cls in (a.uberon_id, a.taxon_id, a.stage_id):
            if cls not in declared:
                declared.add(cls)
                lines.append(f"Declaration(Class({cls}))")
    for prop in sorted({a.predicate for a in live} | {IN_TAXON}):
        lines.append(f"Declaration(ObjectProperty({prop}))")
    lines.append("")

    for a in live:
        label = PREDICATES[a.predicate][0]
        lines.append(f"# {a.uberon_label} {label} {a.stage_label} [{a.taxon_label}]")
        lines.append(gci(a))
        lines.append("")

    lines.append(")")
    return "\n".join(lines) + "\n"


def write(axioms: list[Axiom], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(axioms))
